//! Conservative sensitivity bounds for an ideal vector of group-by moments.
//!
//! A coordinate is the exact (real-valued) sum of bounded row contributions.
//! This is *not* a stability analysis of Polars floating-point aggregation:
//! actual summation order and rounding relaxation remain governed by the
//! existing scalar stability maps. This descriptor must not calibrate noise
//! until that additional numerical error is incorporated.

use polars::prelude::{DataType, Expr};

use crate::domains::SeriesDomain;
use crate::error::Fallible;
use crate::measurements::{
    expr_dp_counting_query::DPLenShim,
    expr_dp_frame_len::DPFrameLenShim,
    expr_dp_sum::DPSumShim,
};
use crate::polars::{literal_value_of, match_shim};
use crate::traits::{InfAdd, InfCast, InfMul, InfSqrt};

/// Bounds on one row's contribution to a materialized statistic.
#[allow(dead_code)] // metadata is not used to calibrate noise in this stage
#[derive(Clone, Debug, PartialEq)]
pub(super) struct Coordinate {
    pub name: String,
    pub lower: f64,
    pub upper: f64,
}

impl Coordinate {
    fn magnitude(&self) -> f64 {
        self.lower.abs().max(self.upper.abs())
    }
}

/// A complete description of the recognized moment coordinates. If one
/// aggregate is unsupported, the planner emits no joint descriptor rather
/// than claiming a bound for only part of the released vector.
#[allow(dead_code)] // consumed by future joint-release strategies
#[derive(Clone, Debug)]
pub(super) struct IdealJointSensitivity {
    pub coordinates: Vec<Coordinate>,
}

#[allow(dead_code)] // analytic bounds are tested but not yet used for mechanisms
impl IdealJointSensitivity {
    pub fn from_aggs(
        aggs: &[Expr],
        columns: &[SeriesDomain],
        centered_squares: &[(String, f64)],
    ) -> Fallible<Option<Self>> {
        if aggs.is_empty() {
            return Ok(None);
        }
        let mut coordinates = Vec::with_capacity(aggs.len());

        for agg in aggs {
            let name = agg.clone().meta().output_name()?.to_string();

            // A centered square is generated by the workload planner, not
            // inferred by examining arbitrary arithmetic in the source AST.
            let interval = if let Some((_, upper)) =
                centered_squares.iter().find(|(n, _)| n == &name)
            {
                Some((0.0, *upper))
            } else {
                coordinate_interval(agg, columns)?
            };
            let Some((lower, upper)) = interval else {
                return Ok(None);
            };
            if !lower.is_finite() || !upper.is_finite() || lower > upper {
                return Ok(None);
            }
            coordinates.push(Coordinate { name, lower, upper });
        }
        Ok(Some(Self { coordinates }))
    }

    /// Upper bounds on the L1 and L2 norms of *one* row's ideal vector.
    /// Each coordinate is bounded separately; this does not presume
    /// independence of coordinates from the same source column.
    pub fn per_row_bounds(&self) -> Fallible<(f64, f64)> {
        let (mut l1, mut squared_l2) = (0.0f64, 0.0f64);
        for coordinate in &self.coordinates {
            let magnitude = coordinate.magnitude();
            l1 = l1.inf_add(&magnitude)?;
            squared_l2 = squared_l2.inf_add(&magnitude.inf_mul(&magnitude)?)?;
        }
        Ok((l1, squared_l2.inf_sqrt()?))
    }

    /// Bound ideal summed vectors across changed groups.
    ///
    /// l0: maximum number of changed groups
    /// l1: maximum number of added/deleted rows across groups
    /// li: maximum changed rows in any one group
    ///
    /// For each changed group g, ||sum_{i in g} v_i||_2 <= m_g B_2.
    /// Since sum_g m_g <= l1 and m_g <= li, the concatenated L2 norm
    /// is bounded by B_2 * min(l1, li*sqrt(l0), sqrt(li*l1)).
    /// The L1 bound is B_1*l1. Both bounds apply only to exact sums.
    pub fn ideal_bounds(&self, (l0, l1, li): (u32, u32, u32)) -> Fallible<(f64, f64)> {
        let (row_l1, row_l2) = self.per_row_bounds()?;
        let (l0, l1, li) = (
            f64::inf_cast(l0)?,
            f64::inf_cast(l1)?,
            f64::inf_cast(li)?,
        );
        let l1_bound = row_l1.inf_mul(&l1)?;
        let group_factor = li.inf_mul(&l0.inf_sqrt()?)?;
        let row_factor = li.inf_mul(&l1)?.inf_sqrt()?;
        let l2_factor = l1.min(group_factor).min(row_factor);
        let l2_bound = row_l2.inf_mul(&l2_factor)?;
        Ok((l1_bound, l2_bound))
    }
}

/// Recognize direct-column bounded Int32/Float64 sums and ordinary lengths.
/// Unsupported preprocessing, dtypes and plugins are deliberately opaque.
fn coordinate_interval(
    expr: &Expr,
    columns: &[SeriesDomain],
) -> Fallible<Option<(f64, f64)>> {
    let expr = expr.clone().meta().undo_aliases();

    if match_shim::<DPFrameLenShim, 2>(&expr)?.is_some() {
        return Ok(Some((1.0, 1.0)));
    }

    if let Some([input, _, _]) = match_shim::<DPLenShim, 3>(&expr)? {
        if matches!(input, Expr::Column(_)) {
            return Ok(Some((1.0, 1.0)));
        }
        return Ok(None);
    }

    if let Some([input, lower, upper, _]) = match_shim::<DPSumShim, 4>(&expr)? {
        let Expr::Column(name) = input else {
            return Ok(None);
        };
        let dtype = columns.iter().find(|column| column.name == name).map(|c| c.dtype());
        // Int32 sums are exact if the scalar constructor's overflow check
        // passes. Float64 sums remain descriptive metadata only because
        // their rounding relaxation has not been incorporated.
        return match dtype {
            Some(DataType::Int32) => {
                let Some(l) = literal_value_of::<i32>(&lower).ok().flatten() else {
                    return Ok(None);
                };
                let Some(u) = literal_value_of::<i32>(&upper).ok().flatten() else {
                    return Ok(None);
                };
                Ok(Some((f64::from(l), f64::from(u))))
            }
            Some(DataType::Float64) => {
                let Some(l) = literal_value_of::<f64>(&lower).ok().flatten() else {
                    return Ok(None);
                };
                let Some(u) = literal_value_of::<f64>(&upper).ok().flatten() else {
                    return Ok(None);
                };
                Ok(Some((l, u)))
            }
            _ => Ok(None),
        };
    }
    Ok(None)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::domains::AtomDomain;
    use polars::prelude::{col, lit};
    use crate::polars::{dp_len, PrivacyNamespace};

    #[test]
    fn test_complete_moment_vector() -> Fallible<()> {
        let columns = vec![SeriesDomain::new("x", AtomDomain::<f64>::default())];
        let aggs = vec![
            dp_len(None, false).alias("n"),
            col("x").dp().sum((lit(0.0), lit(10.0)), None).alias("s"),
            col("x").dp().sum((lit(0.0), lit(25.0)), None).alias("q"),
        ];
        let joint = IdealJointSensitivity::from_aggs(
            &aggs, &columns, &[("q".into(), 25.0)],
        )?.expect("all moment coordinates are recognized");
        assert_eq!(joint.coordinates.len(), 3);
        assert_eq!(joint.coordinates[0].name, "n");
        assert_eq!(joint.coordinates[1].lower, 0.0);
        assert_eq!(joint.coordinates[2].upper, 25.0);

        let (row_l1, row_l2) = joint.per_row_bounds()?;
        assert!(row_l1 >= 36.0 && row_l1 < 36.0001);
        assert!(row_l2 >= (1.0 + 100.0 + 625.0f64).sqrt());
        assert!(row_l2 < 27.0);

        let (l1, l2) = joint.ideal_bounds((2, 3, 2))?;
        assert!(l1 >= 108.0 && l1 < 108.001);
        assert!(l2 >= (6.0 * 726.0f64).sqrt());
        assert!(l2 < 67.0);
        Ok(())
    }

    #[test]
    fn test_mixed_workload_is_not_partially_certified() -> Fallible<()> {
        let columns = vec![SeriesDomain::new("x", AtomDomain::<f64>::default())];
        let aggs = vec![
            dp_len(None, false).alias("n"),
            col("x").sum().dp().noise(None).alias("unknown"),
        ];
        assert!(IdealJointSensitivity::from_aggs(&aggs, &columns, &[])?.is_none());
        Ok(())
    }

    #[test]
    fn test_zero_distance_and_sparse_groups() -> Fallible<()> {
        let joint = IdealJointSensitivity {
            coordinates: vec![
                Coordinate { name: "count".into(), lower: 1.0, upper: 1.0 },
            ],
        };
        assert_eq!(joint.ideal_bounds((0, 0, 0))?, (0.0, 0.0));
        let (l1, l2) = joint.ideal_bounds((4, 8, 2))?;
        assert!(l1 >= 8.0);
        assert!(l2 >= 4.0);
        assert!(l2 < 4.0001);
        Ok(())
    }

    #[test]
    fn test_unsupported_source_does_not_emit_metadata() -> Fallible<()> {
        let columns = vec![SeriesDomain::new("x", AtomDomain::<f32>::default())];
        let agg = col("x").dp().sum((lit(0.0), lit(10.0)), None).alias("s");
        assert!(IdealJointSensitivity::from_aggs(&[agg], &columns, &[])?.is_none());
        Ok(())
    }
}
